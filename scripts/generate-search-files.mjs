import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {publicPaths,siteOrigin} from '../server/seo.mjs';
import {seoPages} from '../src/seo-content.mjs';

// The production and development sitemap come from the same public route list.
// Do not fabricate lastmod from the build clock or include private hash routes.
export function renderSitemap(){
 return ['<?xml version="1.0" encoding="UTF-8"?>','<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',...publicPaths.map(path=>`  <url><loc>${siteOrigin}${path}</loc></url>`),'</urlset>',''].join('\n');
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 await writeFile(new URL('../public/sitemap.xml',import.meta.url),renderSitemap());
 const resources=seoPages.map(page=>({path:page.path,label:page.eyebrow.split('·').at(-1).trim()}));
 await writeFile(new URL('../src/seo-resource-index.mjs',import.meta.url),'// Generated by scripts/generate-search-files.mjs; public navigation only.\nexport const seoResources=Object.freeze('+JSON.stringify(resources,null,2)+');\n');
 console.log(`Generated sitemap for ${publicPaths.length} authored public pages.`);
}
