  assert.equal(api.account.ledger[0].status,'refunded');
  console.log('PASS default free examples, shared task charges, failure refunds, concurrent spending and cancellation refunds');

  const before=api.balance;
  globalThis.localStorage={...storage,setItem(){throw new Error('Quota full');}};
  await act(async()=>{result=await api.runTask(quote,async()=>{runs++;},{force:true});});
  assert.equal(result.code,'storage');
  assert.equal(api.balance,before);
  assert.equal(runs,2,'Storage failure must stop the producer and avoid a false charge');
  globalThis.localStorage=storage;
  await act(async()=>renderer.unmount());renderer=null;
  await act(async()=>{renderer=TestRenderer.create(mount(React.createElement(Probe)));});
  assert.equal(api.balance,88);
  console.log('PASS storage failure blocks simulated billing and normal balances survive remount');

  await act(async()=>renderer.unmount());renderer=null;saved.clear();
  const {Editor,WorkflowDialog}=await server.ssrLoadModule('/src/main.jsx');
