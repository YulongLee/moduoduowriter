  await act(async()=>renderer.unmount());renderer=null;
  saved.clear();
  await act(async()=>{renderer=TestRenderer.create(mount(React.createElement(Probe)));});
  let runs=0,result;
  await act(async()=>{await meter.run(async()=>{runs++;});});
  assert.equal(api.balance,300,'Default examples must remain uncharged');
  await act(async()=>api.setEnabled(true));
  await act(async()=>{await meter.run(async()=>{runs++;});});
  assert.equal(api.balance,288);
  await act(async()=>{await meter.run(async()=>{throw new Error('Provider failed');});});
  assert.equal(api.balance,288);
  assert.equal(api.account.ledger[0].status,'refunded');
  const costly=quoteTask({inputChars:50000,outputChars:10000});
  let release,first;
  await act(async()=>{first=api.runTask(costly,()=>new Promise(resolve=>{release=resolve;}));});
  assert.equal(api.balance,88);
  await act(async()=>{result=await api.runTask(costly,async()=>{runs++;});});
  assert.equal(result.code,'insufficient');
  assert.equal(runs,2,'Insufficient credit must stop the producer');
  await act(async()=>{release();await first;});
  let cancelled;
  await act(async()=>{cancelled=meter.run(()=>new Promise(()=>{}));});
  assert.equal(api.balance,76);
