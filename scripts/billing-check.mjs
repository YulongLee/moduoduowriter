  assert.equal(api.balance,0);
  await click(renderer.root.findByProps({'aria-label':'生成创作示例'}));
  assert.ok(findButton(renderer,'查看加油包'),'Insufficient credit must show a useful funding path');
  assert.equal(api.balance,0);
  await act(async()=>renderer.root.findByProps({'aria-label':'章节正文'}).props.onChange({target:{value:'额度用完，仍能写自己的故事。'}}));
  assert.ok(changed,'Manual editing must remain available with an empty balance');
  await act(async()=>renderer.unmount());renderer=null;saved.clear();
